const list = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const page = list.find((t) => t.type === "page" && t.webSocketDebuggerUrl);
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0;
const send = (m, p = {}) => new Promise((res) => { const mid = ++id; const on = (e) => { const x = JSON.parse(e.data); if (x.id === mid) { ws.removeEventListener("message", on); res(x.result); } }; ws.addEventListener("message", on); ws.send(JSON.stringify({ id: mid, method: m, params: p })); });
await new Promise((r) => ws.addEventListener("open", r, { once: true }));
const ev = async (e) => { const r = await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }); if (r?.exceptionDetails) return "抛错:" + (r.exceptionDetails.text); return r?.result?.value; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await ev(`(() => { const q=document.getElementById("q"); q.value=""; q.dispatchEvent(new Event("input",{bubbles:true})); return 1; })()`);
await wait(4000);
const sample = await ev(`(() => { const r=[...document.querySelectorAll(".row-item")][3]; return r? r.textContent.replace(/\s+/g," ").trim().slice(0,40) : "无行"; })()`);
console.log("第 4 行内容：", sample);
const word = (sample.match(/[A-Za-z0-9_]{5,}/) || [""])[0];
console.log("拿这行的词去搜：", word);
await ev(`(() => { const q=document.getElementById("q"); q.value=${JSON.stringify(word)}; q.dispatchEvent(new Event("input",{bubbles:true})); return 1; })()`);
await wait(5000);
console.log("搜完行数：", await ev(`document.querySelectorAll(".row-item").length`));
console.log("有没有报错条：", await ev(`[...document.querySelectorAll(".rows,#rows,.list-msg,#msg,.dim")].map(e=>e.textContent.trim()).filter(t=>t&&t.length<70).slice(0,3).join(" ⏎ ")`));
ws.close();
