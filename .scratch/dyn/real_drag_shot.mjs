import fs from "node:fs";
import crypto from "node:crypto";
const list = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const page = list.find(p => p.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) pending.get(m.id)(m); };
const call = (method, params) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async e => (await call("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true })).result?.result?.value;
const nap = ms => new Promise(r => setTimeout(r, ms));
const shot = async f => { const r = await call("Page.captureScreenshot", { format: "png" }); fs.writeFileSync(f, Buffer.from(r.result.data, "base64")); };
const md5 = f => crypto.createHash("md5").update(fs.readFileSync(f)).digest("hex").slice(0, 10);
await ev(`document.getElementById('animCanvas').scrollIntoView({block:'center'})`);
await nap(700);
const box = JSON.parse(await ev(`(()=>{const e=document.getElementById('animFrame');const r=e.getBoundingClientRect();return JSON.stringify({x:r.x,y:r.y,w:r.width,h:r.height})})()`));
const y = box.y + box.h / 2;
const at = f => box.x + box.w * f;
const drag = async f => {
  await call("Input.dispatchMouseEvent", { type: "mousePressed", x: at(f), y, button: "left", clickCount: 1 });
  await call("Input.dispatchMouseEvent", { type: "mouseReleased", x: at(f), y, button: "left", clickCount: 1 });
  await nap(2600);
  return await ev(`document.getElementById('animFrame').value`);
};
const v1 = await drag(0.05); await shot("drag_a.png");
const v2 = await drag(0.95); await shot("drag_b.png");
const a = md5("drag_a.png"), b = md5("drag_b.png");
console.log("滑杆 " + v1 + " → " + v2 + "   图 " + a + " / " + b + "   " + (a === b ? "拖了不重画（真缺陷）" : "会重画（之前的假事件不算数）"));
ws.close();
