const list = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const page = list.find((t) => t.type === "page" && t.webSocketDebuggerUrl);
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0;
const msgs = [];
const send = (m, p = {}) => new Promise((res) => { const mid = ++id; const on = (e) => { const x = JSON.parse(e.data); if (x.id === mid) { ws.removeEventListener("message", on); res(x.result); } }; ws.addEventListener("message", on); ws.send(JSON.stringify({ id: mid, method: m, params: p })); });
await new Promise((r) => ws.addEventListener("open", r, { once: true }));
ws.addEventListener("message", (e) => { const x = JSON.parse(e.data); if (x.method === "Runtime.exceptionThrown") msgs.push("异常: " + ((x.params.exceptionDetails.exception || {}).description || x.params.exceptionDetails.text || "").split("\n")[0]); });
await send("Runtime.enable");
const ev = async (e) => { const r = await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }); if (r?.exceptionDetails) return "抛错:" + (r.exceptionDetails.text); return r?.result?.value; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
console.log("标题：", await ev("document.title"));
console.log("主视图标签：", await ev("[...document.querySelectorAll('.view-tab,.main-tab,[data-view]')].map(b=>b.textContent.trim()).join('|').slice(0,60)"));
console.log("清空搜索后行数：", await ev(`(() => { const q=document.getElementById("q"); if(!q) return "没有 #q"; q.value=""; q.dispatchEvent(new Event("input",{bubbles:true})); return "清了"; })()`));
await wait(4000);
console.log("行数：", await ev(`document.querySelectorAll(".row-item").length`));
console.log("列表容器有没有内容：", await ev(`(() => { const l=document.getElementById("list")||document.querySelector(".rows,#rows"); return l? (l.id||l.className)+" 子节点 "+l.children.length : "找不到列表容器"; })()`));
console.log("材质标签在不在：", await ev(`!!document.querySelector('[data-tab="material"]')`));
console.log("状态栏：", await ev(`(document.querySelector(".status,.foot,#status")||{}).textContent`));
await wait(500);
console.log("页面异常：", msgs.slice(0,4).join(" ⏎ ") || "无");
ws.close();
